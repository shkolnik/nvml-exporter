pub fn find(name: &str) -> Option<&'static MetricDef> {
    CATALOG.iter().find(|m| m.name == name)
}

#[derive(Debug, Clone, PartialEq)]
pub struct Sample {
    pub name: &'static str,
    pub labels: Vec<(&'static str, String)>,
    pub value: f64,
}

impl Sample {
    pub fn global(name: &'static str, value: f64) -> Self {
        Sample {
            name,
            labels: Vec::new(),
            value,
        }
    }

    pub fn gpu(name: &'static str, gpu: u32, value: f64) -> Self {
        Sample {
            name,
            labels: vec![("gpu", gpu.to_string())],
            value,
        }
    }

    #[must_use]
    pub fn with_label(mut self, key: &'static str, value: impl Into<String>) -> Self {
        self.labels.push((key, value.into()));
        self
    }
}

pub fn render_docs() -> String {
    let mut out = String::from(
        "# Metrics\n\nThis file is generated by `tests/catalog.rs` \
         (`UPDATE_DOCS=1 cargo test --test catalog` regenerates it).\n\n\
         | Name | Type | Per GPU | Help |\n|---|---|---|---|\n",
    );
    for m in CATALOG {
        let per_gpu = if m.per_gpu { "yes" } else { "no" };
        let _ = writeln!(
            out,
            "| `{}` | {} | {} | {} |",
            m.name,
            m.kind.as_str(),
            per_gpu,
            m.help
        );
    }
    out
}
