//! The metric catalog (design §4.4): every series the exporter can emit, and its docs table.

use std::fmt::Write as _;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Kind {
    Gauge,
    Counter,
}

impl Kind {
    pub fn as_str(self) -> &'static str {
        match self {
            Kind::Gauge => "gauge",
            Kind::Counter => "counter",
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct MetricDef {
    pub name: &'static str,
    pub help: &'static str,
    pub kind: Kind,
    pub per_gpu: bool,
}

const fn global(name: &'static str, help: &'static str, kind: Kind) -> MetricDef {
    MetricDef {
        name,
        help,
        kind,
        per_gpu: false,
    }
}

const fn gpu(name: &'static str, help: &'static str, kind: Kind) -> MetricDef {
    MetricDef {
        name,
        help,
        kind,
        per_gpu: true,
    }
}

